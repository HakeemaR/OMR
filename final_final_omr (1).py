    def plot_grading_confusion_matrix(self, comparison: Dict, save_path="grading_cm.png"):
        """
        Confusion matrix for question-level predictions (A–D).
        Includes only questions with a single predicted option and known correct option.
        """
        labels = ["A", "B", "C", "D"]
        y_true, y_pred = [], []

        for q, res in comparison.get("detailed_results", {}).items():
            ca = res.get("correct_answer")
            sa = res.get("student_answer")
            if isinstance(sa, str) and sa in labels and ca in labels:
                y_true.append(ca)
                y_pred.append(sa)

        if not y_true:
            print("No comparable questions to plot a grading confusion matrix.")
            return

        cm = confusion_matrix(y_true, y_pred, labels=labels)
        fig, ax = plt.subplots()
        disp = ConfusionMatrixDisplay(cm, display_labels=labels)
        disp.plot(ax=ax, colorbar=False)
        ax.set_title("Grading Confusion Matrix (A–D)")
        plt.tight_layout()
        plt.savefig(save_path, dpi=200)
        print(f"Saved: {save_path}")

    def plot_grading_roc_auc(self, results: Dict, answer_key: Dict, save_prefix="grading"):
        """
        One-vs-rest ROC & AUC for A–D using per-option 'confidence' scores from results.
        """
        labels = ["A", "B", "C", "D"]
        label_to_idx = {l: i for i, l in enumerate(labels)}

        y_true_idx = []
        y_scores = []

        for q, opts in results.items():
            ca = answer_key.get(q)
            if ca not in labels:
                continue

            # Collect scores in A,B,C,D order
            scores = []
            ok = True
            for l in labels:
                d = opts.get(l, {})
                if "confidence" not in d:
                    ok = False
                    break
                scores.append(float(d["confidence"]))
            if not ok:
                continue

            y_true_idx.append(label_to_idx[ca])
            y_scores.append(scores)

        if not y_scores:
            print("No scores available to compute grading ROC/AUC.")
            return

        y_scores = np.asarray(y_scores)                     # (N, 4)
        y_true_bin = label_binarize(y_true_idx, classes=[0, 1, 2, 3])  # (N, 4)

        fpr, tpr, roc_auc = {}, {}, {}
        for i, l in enumerate(labels):
            fpr[i], tpr[i], _ = roc_curve(y_true_bin[:, i], y_scores[:, i])
            roc_auc[i] = auc(fpr[i], tpr[i])

        macro_auc = float(np.mean([roc_auc[i] for i in range(4)]))

        plt.figure()
        for i, l in enumerate(labels):
            plt.plot(fpr[i], tpr[i], label=f"{l} (AUC={roc_auc[i]:.3f})")
        plt.plot([0, 1], [0, 1], "--")
        plt.xlabel("False Positive Rate")
        plt.ylabel("True Positive Rate")
        plt.title(f"Grading ROC (One-vs-Rest) • Macro AUC={macro_auc:.3f}")
        plt.legend(loc="lower right")
        plt.tight_layout()
        out_path = f"{save_prefix}_roc.png"
        plt.savefig(out_path, dpi=200)
        print(f"Saved: {out_path}")
        print("Per-class AUC:", {labels[i]: round(roc_auc[i], 4) for i in range(4)})
        print(f"Macro-average AUC: {macro_auc:.4f}")

