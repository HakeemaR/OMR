# ----------------------------- Bubble CNN -----------------------------

class BubbleClassifierCNN:
    """
    CNN model for classifying bubble markings (Marked vs Unmarked)
    """
    def __init__(self, input_size=(32, 32, 1)):
        self.input_size = input_size
        self.model = None
        self.history = None
        self.last_val = None
        # --- Added: store test set + per-epoch test metrics ---
        self.last_test = None
        self.test_metrics = {"loss": [], "accuracy": []}
        # ------------------------------------------------------
        self.build_model()

    def build_model(self):
        """Build a compact CNN for bubble classification"""
        self.model = models.Sequential([
            layers.Conv2D(32, (3, 3), activation='relu', input_shape=self.input_size),
            layers.MaxPooling2D((2, 2)),

            layers.Conv2D(64, (3, 3), activation='relu'),
            layers.MaxPooling2D((2, 2)),

            layers.Conv2D(64, (3, 3), activation='relu'),

            layers.Flatten(),
            layers.Dense(64, activation='relu'),
            layers.Dropout(0.5),
            layers.Dense(1, activation='sigmoid')  # Binary output
        ])
        self.model.compile(optimizer=Adam(learning_rate=0.001),
                           loss='binary_crossentropy',
                           metrics=['accuracy'])

    def preprocess_bubble_image(self, bubble_img: np.ndarray) -> np.ndarray:
        """Resize to 32x32x1, normalize to [0,1], add batch dim"""
        if bubble_img.ndim == 3:
            bubble_img = cv2.cvtColor(bubble_img, cv2.COLOR_BGR2GRAY)
        resized = cv2.resize(bubble_img, self.input_size[:2])
        normalized = resized.astype('float32') / 255.0
        normalized = normalized.reshape(self.input_size)  # (H,W,1)
        return np.expand_dims(normalized, axis=0)  # (1,H,W,1)

    def predict_marking(self, bubble_img: np.ndarray) -> Tuple[bool, float]:
        """Predict if bubble is marked (True/False) and confidence"""
        processed_img = self.preprocess_bubble_image(bubble_img)
        prediction = float(self.model.predict(processed_img, verbose=0)[0][0])
        is_marked = prediction > 0.5
        confidence = prediction if is_marked else (1.0 - prediction)
        return is_marked, confidence

    def generate_synthetic_training_data(self, num_samples=2000, seed=42):
        """Generate synthetic circles (marked/unmarked) for quick training"""
        X, y = [], []
        rng = np.random.default_rng(seed)

        for _ in range(num_samples):
            img = np.ones((32, 32), dtype=np.uint8) * 255
            cv2.circle(img, (16, 16), 12, 0, 2)

            is_marked = bool(rng.integers(0, 2))
            if is_marked:
                fill_intensity = int(rng.integers(50, 150))
                cv2.circle(img, (16, 16), 10, fill_intensity, -1)
                y.append(1)
            else:
                noise = rng.normal(0, 10, img.shape)
                img = np.clip(img + noise, 0, 255)
                y.append(0)

            noise = rng.normal(0, 5, img.shape)
            img = np.clip(img + noise, 0, 255).astype(np.uint8)
            X.append(img)

        X = np.array(X).reshape(-1, 32, 32, 1) / 255.0
        y = np.array(y, dtype=np.float32)
        return X, y

    def train_model(self, epochs=10, validation_split=0.2):
        """Train CNN on synthetic data and store history + validation set"""
        print("Generating synthetic training data...")
        X, y = self.generate_synthetic_training_data(2000)

        X_train, X_val, y_train, y_val = train_test_split(
            X, y, test_size=validation_split, random_state=42, stratify=y
        )

        # --- Added: create a separate synthetic TEST set ---
        X_test, y_test = self.generate_synthetic_training_data(800, seed=999)
        self.last_test = (X_test, y_test)
        # ---------------------------------------------------

        print("Training CNN model...")

        # --- Added: Keras callback to log TEST loss/accuracy per epoch ---
        class TestMetricsCallback(tf.keras.callbacks.Callback):
            def __init__(self, model_ref, X_t, y_t, sink_dict):
                super().__init__()
                self.model_ref = model_ref
                self.X_t = X_t
                self.y_t = y_t
                self.sink = sink_dict

            def on_epoch_end(self, epoch, logs=None):
                loss, acc = self.model_ref.evaluate(self.X_t, self.y_t, verbose=0)
                self.sink["loss"].append(loss)
                self.sink["accuracy"].append(acc)
                # Optional, quiet print:
                print(f"[Epoch {epoch+1}] test_loss={loss:.4f} test_acc={acc:.4f}")
        # ----------------------------------------------------------------

        history = self.model.fit(
            X_train, y_train,
            epochs=epochs,
            validation_data=(X_val, y_val),
            batch_size=32,
            verbose=1,
            callbacks=[TestMetricsCallback(self.model, X_test, y_test, self.test_metrics)]
        )

        self.history = history
        self.last_val = (X_val, y_val)
        return history

    def save_model(self, filepath="bubble_classifier.h5"):
        self.model.save(filepath)
        print(f"Model saved as {filepath}")

    def load_model(self, filepath="bubble_classifier.h5"):
        if os.path.exists(filepath):
            self.model = tf.keras.models.load_model(filepath)
            print(f"Model loaded from {filepath}")
            return True
        return False

