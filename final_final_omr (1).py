        print("="*80)

        print(f"\nSCORE: {comparison['score']}/{comparison['total_questions']} ({comparison['percentage']:.1f}%)")
        print(f"Correct: {len(comparison['correct'])}")
        print(f"Incorrect: {len(comparison['incorrect'])}")
        print(f"Unanswered: {len(comparison['unanswered'])}")
        print(f"Multiple Marked: {len(comparison['multiple_marked'])}")

        p = comparison['percentage']
        if p >= 90: grade = "A+"
        elif p >= 85: grade = "A"
        elif p >= 80: grade = "A-"
        elif p >= 75: grade = "B+"
        elif p >= 70: grade = "B"
        elif p >= 65: grade = "B-"
        elif p >= 60: grade = "C+"
        elif p >= 55: grade = "C"
        elif p >= 50: grade = "C-"
        else: grade = "F"
        print(f"\nESTIMATED GRADE: {grade}")

        if show_detailed:
            print("\n" + "="*50)
            print("DETAILED RESULTS BY BATCH")
            print("="*50)

            batches = {"1-10": [], "11-20": [], "21-30": [], "31-40": []}
            for q in sorted(comparison['detailed_results'].keys(), key=lambda x: int(x[1:]) if x[1:].isdigit() else 0):
                qn = int(q[1:]) if q[1:].isdigit() else 0
                if 1 <= qn <= 10: batches["1-10"].append(q)
                elif 11 <= qn <= 20: batches["11-20"].append(q)
                elif 21 <= qn <= 30: batches["21-30"].append(q)
                elif 31 <= qn <= 40: batches["31-40"].append(q)

            for batch_name, questions in batches.items():
                if not questions: continue
                print(f"\n{'='*15} BATCH {batch_name} {'='*15}")
                batch_correct = 0
                for q in questions:
                    res = comparison['detailed_results'][q]
                    sym = {'Correct':'✓','Incorrect':'✗','Unanswered':'○','Multiple Marked':'◐','No Answer Key':'?'}\
                          .get(res['status'], '?')
                    print(f"{q}: {str(res['student_answer']):>12} | Correct: {str(res['correct_answer']):>2} | {sym} {res['status']}")
                    if res['status'] == 'Correct':
                        batch_correct += 1
                batch_total = len(questions)
                bperc = (batch_correct / batch_total) * 100 if batch_total else 0.0
                print(f"Batch Score: {batch_correct}/{batch_total} ({bperc:.1f}%)")

        if comparison['incorrect']:
            print(f"\nINCORRECT ANSWERS: {', '.join(comparison['incorrect'])}")
        if comparison['unanswered']:
            print(f"UNANSWERED: {', '.join(comparison['unanswered'])}")
        if comparison['multiple_marked']:
            print(f"MULTIPLE MARKED: {', '.join(comparison['multiple_marked'])}")

